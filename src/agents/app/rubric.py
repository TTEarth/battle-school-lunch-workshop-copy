def area_instructions(area: RubricArea) -> str:
    """영역 담당 에이전트의 시스템 지시문을 생성한다."""
    return (
        f"당신은 학교 급식 비교 평가에서 '{area.name}' 영역(가중치 {area.weight}%)을 "
        f"전담하는 {area.agent_name} 입니다.\n"
        f"{area.focus}\n{COMMON_RULES}\n"
        "두 학교의 같은 날짜 중식 데이터가 주어지면 학교별로 1~5점 척도 점수와 "
        "한국어 근거를 작성하세요. 평가에 필요한 데이터가 입력에 없으면 학교별 점수 대신 "
        "채점 불가를 보고하세요.\n"
        "반드시 아래 JSON 형식으로만 응답하세요. JSON 외의 텍스트를 출력하지 마세요.\n"
        "{\n"
        '  "not_scorable": false,\n'
        '  "not_scorable_reason": null,\n'
        '  "schools": [\n'
        '    {"school_code": "<학교 코드>", "score": <1~5 정수>, "rationale": "<근거>"},\n'
        '    {"school_code": "<학교 코드>", "score": <1~5 정수>, "rationale": "<근거>"}\n'
        "  ]\n"
        "}\n"
        '채점 불가일 때는 {"not_scorable": true, "not_scorable_reason": "<이유>", "schools": []} 형식으로 응답하세요.'
    )


